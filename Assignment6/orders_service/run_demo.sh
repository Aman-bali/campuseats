#!/usr/bin/env bash
# Regenerates ../transcript.txt - a live curl -i run of every success and failure path.
#   bash run_demo.sh            (needs: pip install -r requirements.txt)
cd "$(dirname "$0")"
OUT=../transcript.txt
LOGS=${DEMO_LOGS:-$(mktemp -d)}
PIDS=()
cleanup() { kill "${PIDS[@]}" 2>/dev/null; }
trap cleanup EXIT

start() {  # start NAME ENV... -- CMD
  local name=$1; shift
  env "$@" >"$LOGS/$name.log" 2>&1 &
  PIDS+=($!)
}
for p in 5001 5002 5003 5004 5005 5006 5007 5008 5009; do
  if (exec 3<>/dev/tcp/127.0.0.1/$p) 2>/dev/null; then
    echo "port $p is already in use - stop the old process first" >&2; exit 1
  fi
done
start pay_ok        PORT=5002 python3 payments_stub.py
start pay_down      PORT=5004 STUB_FAIL=503 python3 payments_stub.py
start pay_slow      PORT=5007 STUB_SLEEP=10 python3 payments_stub.py
start pay_garbage   PORT=5008 STUB_GARBAGE=1 python3 payments_stub.py
start main          PORT=5001 PAYMENTS_URL=http://localhost:5002 UNAVAILABLE_ITEMS=ITM-99 RATE_LIMIT_MAX=1000 python3 app.py
start ratelimited   PORT=5003 PAYMENTS_URL=http://localhost:5002 RATE_LIMIT_MAX=3 RATE_LIMIT_WINDOW=60 python3 app.py
start down          PORT=5005 PAYMENTS_URL=http://localhost:5004 python3 app.py
start slow          PORT=5009 PAYMENTS_URL=http://localhost:5007 python3 app.py
start garbage       PORT=5006 PAYMENTS_URL=http://localhost:5008 python3 app.py
for p in 5001 5002 5003 5004 5005 5006 5007 5008 5009; do   # wait until every server answers
  for _ in $(seq 50); do (exec 3<>/dev/tcp/127.0.0.1/$p) 2>/dev/null && break; sleep 0.1; done
done

B=http://localhost:5001
GOOD='{"studentId":"S-20251651015","address":"Hostel B, Room 214","cardToken":"tok_4242c9a1b7","items":[{"itemId":"ITM-17","name":"Masala Dosa","quantity":2,"unitPrice":"60.00"},{"itemId":"ITM-04","name":"Filter Coffee","quantity":1,"unitPrice":"25.00"}]}'
H='Content-Type: application/json'

: >"$OUT"
say()  { printf '\n%s\n' "$*" >>"$OUT"; }
banner() { printf '%s\n' "$*" >>"$OUT"; }
step() {  # step "title" curl-args...   (prints the command, then the live response)
  local title=$1; shift
  { printf '\n# %s\n$ curl -i -s' "$title"
    for a in "$@"; do case $a in *[\ \{\"\<\&\?]*) printf " '%s'" "$a";; *) printf ' %s' "$a";; esac; done
    printf '\n'; } >>"$OUT"
  curl -i -s "$@" | tr -d '\r' | grep -v -E '^(Server|Date|Connection):' >>"$OUT"
  printf '\n' >>"$OUT"
}

banner "================================================================"
banner " CampusEats Orders - Assignment 6 transcript (live curl -i run)"
banner " generated by run_demo.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
banner " (Server/Date/Connection headers removed for readability)"
banner "================================================================"

say "################ D1 - SUCCESS ################"
step "D1  Happy path: 201 + Location + JSON body" -X POST $B/orders -H "$H" -H 'Idempotency-Key: demo-key-001' -d "$GOOD"
step "D1  Follow the Location header: 200" $B/orders/ORD-0001

say "################ D2 - FAILURES (status + Problem Details) ################"
step "D2.1 Empty cart -> 422 empty-cart" -X POST $B/orders -H "$H" -d '{"studentId":"S-1","address":"Hostel B","cardToken":"tok_4242","items":[]}'
step "D2.2 Quantity <= 0 -> 422 with field error" -X POST $B/orders -H "$H" -d '{"studentId":"S-1","address":"Hostel B","cardToken":"tok_4242","items":[{"itemId":"ITM-17","name":"Masala Dosa","quantity":0,"unitPrice":"60.00"}]}'
step "D2.3 TWO bad fields at once (address missing + qty -2) -> one 422 listing both" -X POST $B/orders -H "$H" -d '{"studentId":"S-1","cardToken":"tok_4242","items":[{"itemId":"ITM-17","name":"Masala Dosa","quantity":-2,"unitPrice":"60.00"}]}'
step "D2.4 Unknown id -> 404 order-not-found" $B/orders/ORD-9999
step "D2.5 Cancel (first time) -> 201" -X POST $B/orders/ORD-0001/cancellation -H "$H" -d '{"reason":"Changed my mind"}'
step "D2.5 Cancel again -> 409 illegal-transition" -X POST $B/orders/ORD-0001/cancellation -H "$H" -d '{"reason":"Changed my mind"}'
for i in 1 2 3 4; do
  step "D2.6 Rate limit (instance allows 3 per 60 s): request $i" http://localhost:5003/orders
done
step "D2.7 Item sold out -> 422 item-unavailable" -X POST $B/orders -H "$H" -d '{"studentId":"S-1","address":"Hostel B","cardToken":"tok_4242","items":[{"itemId":"ITM-99","name":"Special Thali","quantity":1,"unitPrice":"90.00"}]}'
step "D2.8 Card declined -> 422 payment-declined" -X POST $B/orders -H "$H" -d '{"studentId":"S-1","address":"Hostel B","cardToken":"tok_declined","items":[{"itemId":"ITM-17","name":"Masala Dosa","quantity":1,"unitPrice":"60.00"}]}'
step "D2.9 Bad query parameter -> 422" "$B/orders?status=bogus"
step "D2.10 Malformed JSON -> 400" -X POST $B/orders -H "$H" -d '{"studentId":'
step "D2.11 Wrong Content-Type -> 415" -X POST $B/orders -H 'Content-Type: text/plain' -d 'hello'
step "D2.12 DELETE is not supported -> 405 + Allow" -X DELETE $B/orders/ORD-0001
step "D2.13 PATCH is not supported -> 405 + Allow" -X PATCH $B/orders/ORD-0001 -H "$H" -d '{"status":"cancelled"}'
step "D2.14 Payments down -> 503 + Retry-After, nothing stored (see D4 for timing)" -X POST http://localhost:5005/orders -H "$H" -d "$GOOD"
step "D2.15 Unexpected fault (Payments returns garbage) -> clean 500, no internals" -X POST http://localhost:5006/orders -H "$H" -d "$GOOD"
{ printf '# ... and what the SERVER LOG kept (never sent to the client):\n'
  grep -E "unhandled error|Error|campus_admin" "$LOGS/garbage.log" | head -4 | cut -c1-200
  printf '  [full stack trace is in the log: %s lines]\n\n' "$(grep -c . "$LOGS/garbage.log")"; } >>"$OUT"

say "################ D3 - CONTENT NEGOTIATION ################"
step "D3.1 Accept: application/xml -> 200 XML" $B/orders/ORD-0001 -H 'Accept: application/xml'
step "D3.2 Accept: application/xml on a list" $B/orders -H 'Accept: application/xml'
step "D3.3 Accept: text/html -> 406" $B/orders/ORD-0001 -H 'Accept: text/html'
step "D3.4 q-values: xml;q=0.9, json;q=0.5 -> XML" $B/orders/ORD-0001 -H 'Accept: application/xml;q=0.9, application/json;q=0.5'
step "D3.5 Errors follow Accept too (404 as problem+xml)" $B/orders/ORD-9999 -H 'Accept: application/xml'
step "D3.6 No Accept header (default JSON)" $B/orders/ORD-0001

say "################ D4 - NO REGRESSIONS ################"
say "--- Idempotency (Assignment 4) ---"
step "D4.1a First POST with a fresh key -> 201 (charges once)" -X POST $B/orders -H "$H" -H 'Idempotency-Key: demo-key-002' -d "$GOOD"
step "D4.1b Same key + same body again -> original order, Idempotent-Replay: true" -X POST $B/orders -H "$H" -H 'Idempotency-Key: demo-key-002' -d "$GOOD"
step "D4.2 Same key + DIFFERENT body -> 422 idempotency-key-reused" -X POST $B/orders -H "$H" -H 'Idempotency-Key: demo-key-002' -d "${GOOD/S-20251651015/S-OTHER}"
{ printf '# Payments stub log - ONE charge per key (demo-key-001 and demo-key-002), despite 4 POSTs in total:\n'; grep CHARGE "$LOGS/pay_ok.log"; printf '\n'; } >>"$OUT"
say "--- Timeouts / retries (Assignment 4: connect 1 s, read 3 s, 4 attempts, backoff) ---"
{ printf '# D4.3 Payments outage: 4 attempts with backoff, then 503 (timing shown)\n$ curl -i -s -w "total time: %%{time_total}s\\n" -X POST localhost:5005/orders ...\n'; } >>"$OUT"
curl -i -s -w 'total time: %{time_total}s\n' -X POST http://localhost:5005/orders -H "$H" -d "$GOOD" | tr -d '\r' | grep -v -E '^(Server|Date|Connection):' >>"$OUT"
{ printf '\n# D4.4 Payments hangs (read timeout 3 s x 4 attempts) -> 503, request does not hang forever\n$ curl -i -s -w "total time: %%{time_total}s\\n" -X POST localhost:5009/orders ...\n'; } >>"$OUT"
curl -i -s -w 'total time: %{time_total}s\n' -X POST http://localhost:5009/orders -H "$H" -d "$GOOD" | tr -d '\r' | grep -v -E '^(Server|Date|Connection):' >>"$OUT"
{ printf '\n# D4.5 After the failed attempts nothing was stored:\n$ curl -s localhost:5005/orders\n'; curl -s http://localhost:5005/orders; } >>"$OUT"
{ printf '\n# D4.6 Automated suite:\n$ python -m pytest tests -q\n'; python3 -m pytest tests -q 2>&1 | tail -3; } >>"$OUT"
echo "wrote $OUT"
